// Generates src/data.js from the live origin, so the mirror's message payload
// and canonical text are byte-faithful to the source beacon.
//
//   node scripts/gen.js [originUrl]
//
// The origin defaults to the canonical BEACON-1 address. Anything that could
// drift (the message body, the beacon_id, the canonical text, the shard) is
// pulled from the origin and embedded verbatim. Only the surface URLs that
// point back at a reader are rewritten at request time.

import { writeFile, mkdir } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { createHash } from "node:crypto";

const here = dirname(fileURLToPath(import.meta.url));
const out = resolve(here, "..", "src", "data.js");

const ORIGIN = (process.argv[2] || "https://site-4454a711e74848acafd54d717b462df7.freebuff.page").replace(/\/+$/, "");

async function get(path) {
  const res = await fetch(ORIGIN + path);
  if (!res.ok) throw new Error(`${path} -> ${res.status}`);
  return res.text();
}

/** Raw bytes of the canonical text, so the hash is over bytes and not over a
 *  re-encoded string (a BOM or a CRLF would change it). */
async function getBytes(path) {
  const res = await fetch(ORIGIN + path);
  if (!res.ok) throw new Error(`${path} -> ${res.status}`);
  return new Uint8Array(await res.arrayBuffer());
}

const [beaconTxt, beaconJsonTxt, shardTxt, llmsTxt, robotsTxt, feedTxt, sitemapTxt, agentsTxt] =
  await Promise.all([
    get("/beacon.txt"),
    get("/.well-known/beacon.json"),
    get("/shard.txt"),
    get("/llms.txt"),
    get("/robots.txt"),
    get("/feed.xml"),
    get("/sitemap.xml"),
    get("/AGENTS.md"),
  ]);

const beaconBytes = await getBytes("/beacon.txt");
const sha256 = createHash("sha256").update(beaconBytes).digest("hex");
const beaconJson = JSON.parse(beaconJsonTxt);

// The bytes must be what we embedded, or the mirror would publish a text
// whose hash does not match the beacon_id it claims.
const embedded = new TextEncoder().encode(beaconTxt);
if (embedded.length !== beaconBytes.length) {
  throw new Error(
    `beacon.txt round-trip mismatch: ${embedded.length} bytes embedded vs ${beaconBytes.length} fetched`
  );
}

if (beaconJson.hash_full && beaconJson.hash_full !== sha256) {
  console.warn(
    `warn: beacon.txt sha256 ${sha256} != declared hash_full ${beaconJson.hash_full}`
  );
}
if (beaconJson.beacon_id !== `sha256:${sha256.slice(0, 16)}`) {
  console.warn(`warn: beacon_id ${beaconJson.beacon_id} does not match beacon.txt hash`);
}

const banner = `// GENERATED by scripts/gen.js -- do not edit by hand.
// Source origin: ${ORIGIN}
// beacon.txt sha256: ${sha256}
`;

const body = `export const ORIGIN = ${JSON.stringify(ORIGIN)};
export const BEACON_SHA256 = ${JSON.stringify(sha256)};
export const BEACON_ID = ${JSON.stringify(beaconJson.beacon_id)};

// The canonical message, embedded verbatim.
export const BEACON_TXT = ${JSON.stringify(beaconTxt)};

// The full BEACON-1 descriptor, verbatim. The worker rewrites only the
// surface URLs that a reader should follow to this mirror.
export const BEACON_JSON = ${JSON.stringify(beaconJson, null, 2)};

// The one-line shard, verbatim. It carries the canonical address so that a
// copy of it still sends replies home.
export const SHARD = ${JSON.stringify(shardTxt)};

export const LLMSTXT = ${JSON.stringify(llmsTxt)};
export const ROBOTS = ${JSON.stringify(robotsTxt)};
export const FEED = ${JSON.stringify(feedTxt)};
export const SITEMAP = ${JSON.stringify(sitemapTxt)};
export const AGENTSMD = ${JSON.stringify(agentsTxt)};
`;

await mkdir(dirname(out), { recursive: true });
await writeFile(out, banner + body, "utf8");
console.log(`wrote ${out}`);
console.log(`beacon_id ${beaconJson.beacon_id} sha256 ${sha256}`);
